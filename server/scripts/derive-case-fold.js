/**
 * Derives the case-fold override table. Run: node server/scripts/derive-case-fold.js
 *
 * WHY A TABLE AT ALL: /iu uses simple case FOLDING, String#toLowerCase is lowercase
 * MAPPING. Different Unicode operations — scf(µ)=μ but lower(µ)=µ. Roughly 92 code
 * point PAIRS disagree; the generated table below has fewer ENTRIES than that,
 * since it stores only the minimal per-code-point correction (one entry per
 * non-canonical member of a class), not every disagreeing pair. Getting this
 * wrong UNDER-matches, i.e. a term suggestion silently disappears with a green
 * suite.
 *
 * The table is derived here and verified exhaustively by caseFold.test.js. Do not
 * hand-edit server/lib/caseFold.data.js — re-run this.
 */
const fs = require('fs');
const path = require('path');

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const iuEq = (a, b) => new RegExp(`^${esc(a)}$`, 'iu').test(b);

/** Base fold: per-character lowercase, identity when that would change length. */
function baseFold(ch) {
  const l = ch.toLowerCase();
  return l.length === ch.length ? l : ch;
}

function candidates(ch) {
  const seen = new Set([ch]);
  const queue = [ch];
  while (queue.length) {
    const c = queue.pop();
    for (const next of [c.toLowerCase(), c.toUpperCase()]) {
      if ([...next].length !== 1 || seen.has(next)) continue;
      seen.add(next);
      queue.push(next);
    }
  }
  return [...seen];
}

const overrides = new Map();
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const ch = String.fromCodePoint(cp);
  for (const other of candidates(ch)) {
    if (other === ch || !iuEq(ch, other)) continue;
    if (baseFold(ch) === baseFold(other)) continue;
    // Disagreement. Canonicalise the whole /iu class onto ONE representative:
    // the lowest code point among the class's base folds, so the choice is
    // stable regardless of iteration order.
    const cls = candidates(ch).filter((c) => iuEq(ch, c));
    const target = cls.map(baseFold).sort((a, b) => a.codePointAt(0) - b.codePointAt(0))[0];
    for (const c of cls) {
      if (baseFold(c) !== target && c.length === target.length) overrides.set(c, target);
    }
  }
}

// candidates(ch) is a forward-only BFS over per-char toLowerCase/toUpperCase, so it
// is NOT guaranteed to be the full /iu-equivalence class: a code point that is only
// ever a toUpperCase() *result* (e.g. U+0345, U+1FBE — both map to U+0399 going up,
// nothing maps down to either of them) is invisible to every other member's BFS.
// Two such "source-only" nodes in the same /iu class each anchor their own
// candidates() call and can pick different targets (observed: U+0399/U+03B9 picked
// U+0345, but U+1FBE — unreachable from either — independently picked U+03B9).
// Resolve by chasing each override to a fixed point. This only ever COMPOSES edges
// that were already individually iuEq-validated above, so it cannot merge code
// points that /iu treats as distinct (e.g. it must never touch U+0131 "ı", whose
// simple case fold is itself even though 'I'.toLowerCase() reaches it transitively).
for (const [from] of overrides) {
  let target = overrides.get(from);
  const chain = new Set([from]);
  while (overrides.has(target) && !chain.has(target)) {
    chain.add(target);
    target = overrides.get(target);
  }
  overrides.set(from, target);
}

const lines = [...overrides]
  .sort((a, b) => a[0].codePointAt(0) - b[0].codePointAt(0))
  .map(([from, to]) => {
    // The plain-form escape below is exactly 4 hex digits. A code point above 0xFFFF
    // needs a 5th hex digit, and JS does not error on the overflow — it silently
    // reads only the first 4 digits as the escape and treats the 5th as a separate,
    // literal character glued on afterward. So an astral code point emitted through
    // the plain form corrupts silently rather than failing loudly. The braced form
    // (with curly braces around the hex digits) has no digit-count limit and is
    // required above the BMP; kept the familiar padded plain form at/below it so
    // today's (all-BMP) output stays byte-identical.
    const u = (s) => {
      const cp = s.codePointAt(0);
      const hex = cp.toString(16).toUpperCase();
      return cp > 0xffff ? `\\u{${hex}}` : `\\u${hex.padStart(4, '0')}`;
    };
    return `  ['${u(from)}', '${u(to)}'],`;
  });

fs.writeFileSync(
  path.join(__dirname, '..', 'lib', 'caseFold.data.js'),
  `/**
 * GENERATED by server/scripts/derive-case-fold.js — do not hand-edit.
 * Code points where JS simple case FOLDING (what /iu uses) disagrees with
 * lowercase MAPPING (what String#toLowerCase does).
 * Verified exhaustively by server/__tests__/caseFold.test.js.
 */
module.exports = [
${lines.join('\n')}
];
`
);
console.log(`wrote ${overrides.size} overrides`);
