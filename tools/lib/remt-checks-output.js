/**
 * Count the distinct element NAMES a tag-count comparison would look at.
 *
 * This is R1's `examined`, and it is deliberately NOT the number of discrepancies.
 * Mirrors `cnxml-fidelity-check.js`'s own `countTags` normalisation (MathML collapsed to
 * a single `<m:math/>`) so the two cannot drift into counting different things.
 */
export function elementNamesCompared(sourceCnxml, translatedCnxml) {
  const names = (x) =>
    new Set(
      [
        ...String(x)
          .replace(/<m:math[\s\S]*?<\/m:math>/g, '<m:math/>')
          .matchAll(/<([a-zA-Z][a-zA-Z0-9:]*?)[\s>/]/g),
      ].map((m) => m[1])
    );
  const out = names(sourceCnxml);
  for (const n of names(translatedCnxml)) out.add(n);
  return out.size;
}

/**
 * R1 — no UNEXPLAINED element-count discrepancy `01-source` → `03-translated`.
 *
 * ══ WHY ADVISORY, AND IT IS TWO INDEPENDENT REASONS ══════════════════════════════
 * ① **THE SPEC'S SEQUENCING CONSTRAINT IS REAL, AND IT WAS CONFIRMED BY EXECUTION AFTER
 * FIRST BEING TALKED OUT OF.** The spec (`2026-08-13-remt-check-battery.md:270`) says R1
 * cannot be blocking until `fidelity-allowlist.json` is re-derived. It is tempting to
 * import §C82 **L58**'s result here — where the identical-sounding claim about A5's
 * residue allowlist was MEASURED FALSE — and conclude the same. **It does not transfer,
 * and the point of failure is THE KEY.** Residue is `segmentId`-keyed, and element ids
 * come from read-only `01-source`, so a re-extract cannot move them (L58's actual
 * measurement). Fidelity is keyed on the exact triple `(moduleId, tag, diff)` — and
 * `diff` is a MAGNITUDE THE RE-INJECT MOVES. Settled with a two-case experiment on
 * `m68846` in a scratch copy:
 *     CASE A  the loss is fixed  → the row vanishes  → entry orphaned → R1 GREEN
 *     CASE B  diff −2 becomes −3 → the row remains   → entry orphaned AND the module
 *                                                      reads UNEXPLAINED → R1 RED
 * Orphaning and reddening are THE SAME EVENT in case B. All 10 orphans observed today are
 * case A (drifted-magnitude = 0, measured) — but that is a fact about the drift SO FAR,
 * not about the re-MT. **36 entries, chemistry only, vintage 2026-07-06; 26 currently
 * match a live discrepancy, and chemistry's 0/149 rests entirely on those 26 exact
 * magnitudes.**
 *
 * ② **ORGANIC'S ONLY DENOMINATOR IS FIVE MONTHS STALE.** Its 8 comparable
 * `03-translated` files are 100% March 2026 (`7aca8fd0` 03-23, `43c40fce`/`32b178d6`
 * 03-30) while organic's `02-mt-output` moved 2026-08-12 — the translated tree is stale
 * relative to its own MT input. So `6 of 8 = 75%` measures the MARCH injector.
 * **334 of organic's 342 modules have no `03-translated` at all.**
 *
 * ⚠️ RECORD BOTH REASONS. Picking one loses information, and a post-run re-measurement
 * that conflates them is uninterpretable — §C82 L64's shape.
 *
 * ✅ **BUT A LIVE FLOOR SURVIVES THE STALENESS, AND IT IS A CATEGORY RATHER THAN A RATE.**
 * 31 of organic's 41 unexplained units are `<span>` drops across 5 modules (source
 * 10/2/9/2/8 → 0 in every one). `cnxml-extract.js` and `cnxml-inject.js` contain **ZERO**
 * occurrences of the CNXML `<span>` element (positive control: `emphasis` appears 13
 * times in extract and 28 in inject), and `<span>` appears in 0 of 149 chemistry source
 * modules (control: `<para` in 137 of 149). **A saturated 100% is a category, not a
 * result** — this is the split that explains it, and no re-render clears it.
 *
 * ⚠️ ONLY THE TAG-COUNT LEG IS A FINDING. `cnxml-fidelity-check.js:465` exits on a
 * counter incremented only at `:400`, inside the tag-count loop, which is also the sole
 * `classifyDiff` call site. `compareElementOrder` and `compareMathBlocks` are
 * `console.log` warn-only in the tool and stay advisory here — chemistry's 36 math
 * mismatches all have MATCHING BLOCK COUNTS, i.e. they are within-block differences.
 *
 * 🔴 `ctx.fidelityAllowlist` MUST BE LOADED WITH `loadAllowlistOrNull`, NOT
 * `loadAllowlist`. The latter returns `{entries: []}` for a MISSING FILE, for
 * `{"entries": []}` and for `{"entries": null}` — three representations of "nothing"
 * collapsing into one value. Measured: of the six books with an `01-source`, exactly ONE
 * (`efnafraedi-2e`) has a `fidelity-allowlist.json`; **`lifraen-efnafraedi`, a live run
 * target, has none.** Gates are pure, so R1 cannot tell the two apart itself — hence
 * `null` means "no allowlist file" and is reported, never silently treated as
 * zero-tolerance.
 */
export const R1 = defineCheck({
  id: 'R1',
  tier: 3,
  blocking: false,
  version: 1,
  run: (ctx) => {
    const src = ctx?.cnxml;
    const tr = ctx?.translatedCnxml;
    if (typeof src !== 'string' || typeof tr !== 'string') {
      return {
        verdict: VERDICT.SKIPPED,
        examined: 0,
        findings: [],
        message:
          'R1: needs ctx.cnxml (01-source) and ctx.translatedCnxml (03-translated/<track>) as strings',
      };
    }
    // `undefined` is "the loader did not run"; `null` is "the loader ran and there is no
    // file". They are different states and only the second is reportable as a fact.
    const allowlist = ctx?.fidelityAllowlist;
    if (allowlist !== null && (typeof allowlist !== 'object' || Array.isArray(allowlist))) {
      return {
        verdict: VERDICT.SKIPPED,
        examined: 0,
        findings: [],
        message:
          'R1: ctx.fidelityAllowlist must be the parsed allowlist or null — ' +
          'load it with loadAllowlistOrNull(bookDir), never loadAllowlist(bookDir)',
      };
    }
    const examined = elementNamesCompared(src, tr);
    const diffs = compareTagCounts(src, tr);
    const findings = [];
    for (const d of diffs) {
      const verdictForDiff = allowlist
        ? classifyDiff(ctx.module, d.tag, d.diff, allowlist)
        : { status: 'unexplained' };
      if (verdictForDiff.status === 'unexplained') {
        findings.push({
          kind: 'unexplained-tag-count',
          tag: d.tag,
          source: d.source,
          translated: d.translated,
          diff: d.diff,
        });
      }
    }
    // Advisory sub-leg, kept OUT of `findings` on purpose: the tool itself never lets
    // element order reach its exit code, and promoting it here would make this check
    // stricter than the instrument it wraps without a base rate to justify it.
    const order = compareElementOrder(src, tr);
    const movedCount = order && Array.isArray(order.moved) ? order.moved.length : 0;

    const allowNote =
      allowlist === null
        ? 'no fidelity-allowlist.json for this book — NOTHING is pre-explained'
        : `${(allowlist.entries || []).length} allowlist entries`;
    return {
      verdict: findings.length ? VERDICT.FAIL : VERDICT.PASS,
      examined,
      findings,
      message:
        `${findings.length} unexplained of ${diffs.length} tag-count discrepancies over ` +
        `${examined} element names; ${allowNote}; ` +
        `element order: ${movedCount} moved (ADVISORY — warn-only in the tool, never a finding)`,
    };
  },
});

/**
 * R2 — the injector reported no positional-restore attribute mismatch.
 *
 * ══ WHY BLOCKING, AND WHY ITS FIXTURE HAD TO BE SYNTHETIC ════════════════════════
 * Base rate **2 of 166 = 1.20%** (chemistry 2, organic 0) over the 166 of 197 pairs
 * `buildCnxml` can reach — comfortably inside Global Constraint 4's ≤5%. The 31
 * unreachable organic units lack BOTH `01-source` and `02-structure` (31 of 31, executed).
 *
 * 🔴 BUT RULE 4 ALSO REQUIRES A KNOWN-BAD FIXTURE, AND R2's NATURAL ONES EXPIRE ON THE
 * DAY THE LOOP STARTS. Both live must-trips are legacy `{{term}}` modules
 * (`m68709:para:fs-idp47467664`, `m68735:para:fs-idm1670816`); re-extracting those same
 * modules from `01-source` emits `[[term:…|term-000NN]]` instead, and the mismatch
 * disappears. **A check whose entire fixture set is voided by the very re-extract it is
 * meant to gate cannot rest on those fixtures.** So R2's must-trip is SYNTHETIC and is
 * built BY CALLING `buildCnxml` — §C82 L48's rule: build every read-fixture from the real
 * producer, so a producer-side rename surfaces as a red test rather than a silent pass.
 *
 * 🔴 AND THE 1.20% IS BLINDNESS, NOT HEALTH — DOCUMENTED, BOUND BY A TEST, DELIBERATELY
 * NOT FIXED (§C82 L61's shape). Probed against the real producer on new-format input:
 *     duplication   `[[term:X|term-00001]]` ×2  → attrMismatches `[]`, and the OUTPUT
 *                                                 carries a DUPLICATE id
 *     partial loss  3 of 7 markers destroyed    → attrMismatches `[]`, only 4 of 7 survive
 *     total loss    all markers destroyed       → fires correctly
 * ▶ **On new-format input R2 detects ONLY TOTAL PER-SEGMENT MARKER ANNIHILATION.**
 * Duplication and partial loss are structurally invisible whatever the base rate turns
 * out to be. A reader who sees 1.20% and no caveat will read it as health. Widening it is
 * not this task's call — the detector for partial marker damage is Tier 2's `A2b`, which
 * is already blocking and works cross-side.
 *
 * `examined` is SEGMENTS INJECTED, not `attrMismatches.length` — keying it to the finding
 * count would SKIP 164 of 166 modules (98.8%), i.e. the check would report "never ran"
 * on virtually every healthy module while being the one Tier 3 check whose rate qualifies
 * it to block.
 */
export const R2 = defineCheck({
  id: 'R2',
  tier: 3,
  blocking: true,
  version: 1,
  run: (ctx) => {
    const report = ctx?.injectReport;
    // ① the loader did not run, or handed something that is not a report
    if (!report || typeof report !== 'object' || Array.isArray(report)) {
      return {
        verdict: VERDICT.SKIPPED,
        examined: 0,
        findings: [],
        message:
          'R2: ctx.injectReport must be the object buildCnxml() returns ' +
          '(cnxml-inject.js:5154 — exported and I/O-free; the driver calls it)',
      };
    }
    // ② a report that carries no `attrMismatches` KEY is a different state from one
    // carrying an empty array: the first means the producer changed shape under us, the
    // second means the module is clean. Conflating them is §C82 L48's defect.
    if (!Array.isArray(report.attrMismatches)) {
      return {
        verdict: VERDICT.SKIPPED,
        examined: 0,
        findings: [],
        message:
          'R2: injectReport.attrMismatches is absent or not an array — the producer’s ' +
          'shape has changed; re-derive this check against buildCnxml() before trusting it',
      };
    }
    // 🔴 `examined` STAYS `segmentsFound`, AND THE REVIEW'S OBJECTION TO IT IS RECORDED
    // RATHER THAN ACTED ON — because acting on it would re-create the defect the register
    // already decided one tier over.
    // THE OBJECTION, MEASURED AND CORRECT: every one of R2's three legs requires
    // `inlineAttrs[segmentId]` truthy, and over all 166 buildable modules with FRESH
    // extraction only **666 of 23,154 segments (2.88%)** carry such an entry, with
    // **39 of 166 modules (23.5%) carrying none at all**. So `segmentsFound` overstates the
    // population R2 could possibly judge by ~35x.
    // ▶ WHY IT IS STILL THE RIGHT UNIT: keying `examined` to the judgeable sub-count would
    // make 23.5% of modules report `examined 0`, and R2 is BLOCKING — `runTier` turns that
    // into a halt. That is precisely the ~70% false-halt trap `remt-checks-extract.js`'s
    // header records for E4 (L17) and the reason E2/E4/E5 all key `examined` to SEGMENTS
    // INSPECTED and carry their sub-counts in `message`. A module with no inline-attr
    // segments has nothing that COULD mismatch, so PASS is honest there, not a false clean.
    // ▶ THE SUB-COUNT IS REPORTED INSTEAD, whenever the loader supplies `ctx.inlineAttrs`
    // (the driver already has it — it is `extractSegments`' fourth return value and
    // `buildCnxml`'s sixth argument), so a reader can see the judgeable population beside
    // the examined one rather than inferring health from a single number.
    const examined = Number.isInteger(report.segmentsFound) ? report.segmentsFound : 0;
    const judgeable =
      ctx?.inlineAttrs && typeof ctx.inlineAttrs === 'object' && !Array.isArray(ctx.inlineAttrs)
        ? Object.values(ctx.inlineAttrs).filter((v) => v && typeof v === 'object').length
        : null;
    const findings = report.attrMismatches.map((m) => ({
      kind: 'attr-count-mismatch',
      segmentId: m.segmentId,
      family: m.family,
      expected: m.expected,
      found: m.found,
    }));
    return {
      verdict: findings.length ? VERDICT.FAIL : VERDICT.PASS,
      examined,
      findings,
      message:
        `${findings.length} positional-restore attribute mismatch(es) over ${examined} injected ` +
        `segments` +
        (judgeable === null
          ? ' (judgeable population unknown — ctx.inlineAttrs not supplied)'
          : `, of which ${judgeable} carry an inline-attr entry and are judgeable at all`) +
        `. ⚠️ DETECTS ONLY TOTAL per-segment marker annihilation — duplication and ` +
        `partial loss are invisible here; A2b is the cross-side detector for those`,
    };
  },
});

