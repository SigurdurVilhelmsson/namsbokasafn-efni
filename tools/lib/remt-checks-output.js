/**
 * Classify the validator's stderr: is this "the instrument could not run" or a real error?
 *
 * 🔴 EXTRACTED SO IT CAN BE TESTED WHERE THE INSTRUMENT DOES NOT EXIST — which is CI, and
 * every fresh clone. The distinction it draws (instrument-absent vs usage-error) was
 * originally asserted only through the real tool, and THAT TEST WENT RED IN CI while
 * passing on a dev box:
 *   · `experiments/cnxml-validation-gate/external/` (the RelaxNG schema) is gitignored —
 *     **0 tracked files** — and no workflow installs `jing` or `java`;
 *   · `validate-cnxml.js` checks the schema at `:91` and loads the allowlist at `:131`,
 *     **schema first**;
 *   · so on CI a deliberately-bad `--allowlist` never reaches the allowlist check. The tool
 *     dies `FATAL: schema not found`, this classifier converts it, the helper RESOLVES, and
 *     a test asserting a REJECTION fails.
 * ▶ **A guard whose only test needs an instrument CI does not have is a guard CI cannot
 * check** — and conditionally skipping it would leave it out of the loop entirely (§C82
 * L57). Made pure instead, so the classification is bound everywhere and only the
 * environment-dependent half stays in the spawn tests.
 *
 * @param {string} stderr
 * @returns {{instrumentMissing: true, reason: string}|null} null when this is NOT an
 *   instrument-absence — a usage error, which the caller must surface rather than swallow.
 */
export function classifyInstrumentStderr(stderr) {
  const text = String(stderr || '');
  if (!/FATAL: (jing not found|schema not found)/.test(text)) return null;
  return { instrumentMissing: true, reason: text.trim().split('\n')[0] };
}

/**
 * Loader helper — run the RelaxNG gate in a separate process and return its parsed JSON.
 * NOT a gate: it does I/O and spawns, and it exists so `R3` does not have to.
 *
 * 🔴 SPAWN, NOT IMPORT, FOR TWO INDEPENDENT REASONS, both measured:
 * `experiments/cnxml-validation-gate/validate-cnxml.js` has **zero exports**, so there is
 * no importable pure form at all; and `experiments/` is enumerated in NONE of root
 * `LICENSE`'s three licensed paths (`grep -ac experiments LICENSE` → 0, control `server`
 * → 52), so a static import from MIT `tools/` would create an edge into an unlicensed
 * tree. This is G5's resolution reused, and like G5 it creates no edge.
 *
 * ⚠️ THE EXIT CODE IS IGNORED ON PURPOSE — the spawn model at
 * `server/services/publicationService.js:124-184`, and Global Constraint 3 ("never infer
 * a pass from exit code 0"). The verdict is stdout. `cwd` is pinned to the repo root
 * because the tool resolves `--allowlist` relative to cwd (measured: from `server/`, a
 * bare `experiments/...` path dies `FATAL: allowlist not found`).
 *
 * 🔴 EXIT 2 IS "THE INSTRUMENT COULD NOT RUN" AND IS RETURNED AS SUCH, NOT AS CLEAN.
 * Both absence modes are loud and both land here: `FATAL: jing not found on PATH` and
 * `FATAL: schema not found`. R3 turns that into a SKIPPED, and because R3 is blocking a
 * SKIPPED halts the run.
 */
export function spawnSchemaCheck(targets, { repoRoot, allowlist, env } = {}) {
  const root = repoRoot || path.resolve(import.meta.dirname, '..', '..');
  const gateDir = path.join(root, 'experiments', 'cnxml-validation-gate');
  const list = Array.isArray(targets) ? targets : [targets];
  const args = [
    path.join(gateDir, 'validate-cnxml.js'),
    '--json',
    '--allowlist',
    allowlist || path.join(gateDir, 'allowlist.recommended.json'),
    ...list,
  ];
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, args, { cwd: root, env: env || process.env });
    let out = '';
    let err = '';
    child.stdout.on('data', (d) => (out += d));
    child.stderr.on('data', (d) => (err += d));
    child.on('error', (e) => reject(new Error(`spawnSchemaCheck: ${e.message}`)));
    child.on('close', () => {
      // The instrument's own refusals are FATAL: lines on stderr with exit 2. They are a
      // legitimate result of this helper, not an exception — R3 decides what they mean.
      const missing = classifyInstrumentStderr(err);
      if (missing) return resolve(missing);
      try {
        // `targets` is echoed back so a gate can refuse a verdict that does not cover the
        // module it is judging. The payload itself names no file on a clean run.
        resolve({ ...JSON.parse(out), targets: list });
      } catch (e) {
        // A parse failure REJECTS with stderr attached rather than reading as a pass.
        // ⚠️ THE COMMONEST CAUSE IS NOT MALFORMED JSON — it is TRUNCATION. The tool does
        // `console.log(JSON.stringify(...))` and then `process.exit()`, and Node writes
        // stdout to a PIPE asynchronously, so the tail is discarded with the exit code
        // still correct. Measured on the two kept books: 171,714 bytes through a `>`
        // redirect (parses) against exactly 65,536 through a pipe (throws). Fixed in the
        // tool by this task; this message exists so a recurrence is diagnosable.
        reject(
          new Error(
            `spawnSchemaCheck: could not parse --json (${out.length} bytes, ` +
              `${e.message}). If the byte count is a power of two, suspect a truncated pipe. ` +
              `stderr: ${err.trim().slice(0, 500)}`
          )
        );
      }
    });
  });
}
